"""Seed and maintain the editable harness-data directory."""

from __future__ import annotations

import contextlib
import shutil
import subprocess
import threading
from pathlib import Path

from ..paths import ensure_home, harness_dir, write_private
from .defaults import (
    DEFAULT_EFFICIENCY_GUIDE,
    DEFAULT_HARNESS_GUIDE,
    DEFAULT_HARNESS_README,
    DEFAULT_SYSTEM_PROMPT,
    DEFAULT_TOOL_GUIDANCE,
    LEGACY_SYSTEM_PROMPTS,
    LEGACY_TOOL_GUIDANCE,
)

_LOCK = threading.Lock()
_ENSURED: set[str] = set()

_DIRECTORIES = (
    "prompts",
    "tool_guidance",
    "skills",
    "subagents",
    "commands",
    "hooks",
    "profiles",
)


def _write_if_missing(path: Path, content: str) -> None:
    if path.exists():
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    write_private(path, content)


def _ensure_ignore_entry(root: Path, entry: str) -> None:
    path = root / ".gitignore"
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return
    if entry in {line.strip() for line in text.splitlines()}:
        return
    write_private(path, text.rstrip() + f"\n{entry}\n")


def _upgrade_default(path: Path, content: str, legacy: tuple[str, ...]) -> None:
    """Replace an unedited legacy default without touching user edits."""

    if not path.exists():
        return
    try:
        current = path.read_text(encoding="utf-8")
    except (OSError, UnicodeError):
        return
    if current in legacy:
        write_private(path, content)


def _git(root: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", "-C", str(root), *args],
        capture_output=True,
        text=True,
        timeout=15,
        check=False,
    )


def _ensure_git(root: Path) -> None:
    if (root / ".git").exists() or shutil.which("git") is None:
        return
    try:
        if _git(root, "init", "-q").returncode != 0:
            return
        _git(root, "add", "-A")
        _git(
            root,
            "-c",
            "user.name=siwah",
            "-c",
            "user.email=siwah@localhost",
            "commit",
            "-q",
            "-m",
            "harness: initial",
        )
    except (OSError, subprocess.SubprocessError):
        # Git is optional for the local harness; files still work without it.
        return


def ensure_harness() -> Path:
    """Create the default harness data and git repo if absent."""

    root = harness_dir()
    key = str(root.resolve())
    with _LOCK:
        prompt = root / "prompts" / "system.md"
        if key in _ENSURED and prompt.exists():
            return root
        ensure_home()
        for directory in _DIRECTORIES:
            (root / directory).mkdir(parents=True, exist_ok=True)
        _write_if_missing(prompt, DEFAULT_SYSTEM_PROMPT)
        _upgrade_default(prompt, DEFAULT_SYSTEM_PROMPT, LEGACY_SYSTEM_PROMPTS)
        guidance = root / "tool_guidance" / "01-workflow.md"
        _write_if_missing(guidance, DEFAULT_TOOL_GUIDANCE)
        _upgrade_default(guidance, DEFAULT_TOOL_GUIDANCE, LEGACY_TOOL_GUIDANCE)
        _write_if_missing(root / "tool_guidance" / "02-harness.md", DEFAULT_HARNESS_GUIDE)
        _write_if_missing(root / "tool_guidance" / "03-efficiency.md", DEFAULT_EFFICIENCY_GUIDE)
        _write_if_missing(root / "README.md", DEFAULT_HARNESS_README)
        _write_if_missing(
            root / ".gitignore",
            "# Generated by siwah; keep temporary harness artifacts out of history.\n"
            "*.tmp\ntui.json\ncron.json\ncron.run.lock\ncron.store.lock\n"
            "skills/.usage.json\nskills/.usage.lock\n"
            "skills/.curator.json\nskills/.curator.lock\n",
        )
        for entry in (
            "tui.json",
            "cron.json",
            "cron.run.lock",
            "cron.store.lock",
            "skills/.usage.json",
            "skills/.usage.lock",
            "skills/.curator.json",
            "skills/.curator.lock",
        ):
            _ensure_ignore_entry(root, entry)
        _ensure_git(root)
        _ENSURED.add(key)
    return root


def harness_root() -> Path:
    with contextlib.suppress(OSError):
        return ensure_harness()
    return harness_dir()
